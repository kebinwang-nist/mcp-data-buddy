"""CDC MCP server: dataset reads from CDC open data (data.cdc.gov, Socrata SODA API).

The server loads every topic skill ``skills/<topic>/SKILL.md`` (generated by
``build_skills.py``) at import and:

- publishes each as the ``skill://cdc-<...>`` resource and the ``skill-<topic>`` prompt, and
  builds the server instructions from their descriptions;
- adds the ``list_datasets`` and ``describe_dataset`` discovery tools, driven by the endpoint
  indexes and per-dataset sections of the skills;
- makes ``get_dataset`` reject dataset ids no skill lists (with close-match suggestions) and
  maps/charts (pointing at the dataset they are built on), before any HTTP call.

The skill parsing lives in :mod:`servers.cdc.catalog`. Without skill files the server exposes only
``get_dataset``, unvalidated. Set ``"load_skills": false`` on its entry in
``server_config.json`` for the same behavior while keeping the files. Regenerate the skills
with ``uv run python -m servers.cdc.build_skills``.
"""

import inspect
import json
import logging
import ssl
from collections.abc import Sequence
from pathlib import Path

import httpx
import truststore
from fastmcp import FastMCP
from fastmcp.exceptions import ToolError

from servers.cdc.catalog import (
    SodaCatalog,
    format_index,
    merge_catalogs,
    parse_catalog,
)
from servers.skills import Skill, load_nested_skills, register_skill

logger = logging.getLogger(__name__)

_SERVER_DIR = Path(__file__).resolve().parent
_SERVER_CONFIG = _SERVER_DIR.parents[1] / "server_config.json"
_LABEL = "CDC"
_PAGE_LIMIT = 100
_MAX_LIMIT = 50000
_TIMEOUT_SECONDS = 60.0

_DISCOVERY_HINT = (
    "Call list_datasets (optionally with a search term or category) to find a dataset, "
    "describe_dataset to see its columns, row count, tags and freshness, then "
    "get_dataset(dataset_id, select, where, order, group, having, q, limit, offset) to read "
    "rows. Aggregate on the server (select='count(*) as n', group=...) instead of paging "
    "through large datasets, and read the skill's usage tips (prompt skill-<category>) for "
    "known data quirks."
)
_TOOL_HINT = (
    "Use list_datasets to find valid dataset ids and describe_dataset for a dataset's "
    "columns. Unknown ids and maps/charts (which have no data endpoint) are rejected with "
    "suggestions."
)


def _load_entry(name: str) -> dict[str, object]:
    """Return the entry of server ``name`` in ``server_config.json``."""
    servers: list[dict[str, object]] = json.loads(_SERVER_CONFIG.read_text(encoding="utf-8"))
    for server in servers:
        if server["name"] == name:
            return server
    raise KeyError(f"No '{name}' entry in {_SERVER_CONFIG}")


_ENTRY = _load_entry("cdc")
_ENDPOINTS: dict[str, str] = _ENTRY.get("endpoints", {})  # type: ignore[assignment]
_LOAD_SKILLS = bool(_ENTRY.get("load_skills", True))


async def _fetch_dataset(dataset_id: str, params: dict[str, str | int]) -> str:
    """GET ``{base_url}/resource/{dataset_id}.json`` and return the rows as a JSON list.

    Raises:
        ToolError: If the API returns an error status; the message carries the API's error
            body (e.g. ``query.soql.no-such-column``) so the caller can fix the query.
    """
    endpoint = f"{_ENDPOINTS['base_url'].rstrip('/')}/resource/{dataset_id}.json"
    async with httpx.AsyncClient(
        timeout=_TIMEOUT_SECONDS,
        verify=truststore.SSLContext(ssl.PROTOCOL_TLS_CLIENT),
    ) as client:
        response = await client.get(endpoint, params=params)
    if response.is_error:
        raise ToolError(
            f"CDC API returned HTTP {response.status_code} for {dataset_id}: {response.text[:1000]}"
        )
    return json.dumps(response.json())


def _build_catalog(skills: Sequence[Skill]) -> SodaCatalog | None:
    """Merge the catalogs of ``skills``; ``None`` if none of them lists an asset."""
    catalog = merge_catalogs(
        [parse_catalog(s.body, s.path.parent.name, label="CDC") for s in skills]
    )
    if not catalog.assets:
        if skills:
            logger.warning("CDC skills list no datasets; get_dataset won't validate")
        return None
    return catalog


def _instructions(skills: Sequence[Skill]) -> str | None:
    """Build the server instructions from the skill descriptions, or ``None`` without skills."""
    if not skills:
        return None
    parts = [
        "CDC open data (data.cdc.gov). Categories:",
        *(f"- {s.path.parent.name}: {s.description}" for s in skills),
        _DISCOVERY_HINT,
        "Full references: MCP resources " + ", ".join(s.resource_uri for s in skills) + ".",
    ]
    return "\n\n".join(parts)


def _unknown(what: str, suggestions: list[str], total: int) -> ToolError:
    """Build the error for a dataset id the skills do not list."""
    hint = f" Did you mean: {', '.join(suggestions)}?" if suggestions else ""
    return ToolError(
        f"Unknown CDC dataset '{what}'.{hint} Call list_datasets to see all {total} assets."
    )


def create_server(skills: Sequence[Skill] = ()) -> FastMCP:
    """Build the CDC FastMCP server, using the skills if given.

    Args:
        skills: Topic skills (``skills/<topic>/SKILL.md``) whose endpoint indexes and column
            tables back discovery and validation. Empty for the plain ``get_dataset``-only
            server.

    Returns:
        The configured server.
    """
    catalog = _build_catalog(skills)
    mcp = FastMCP("CdcServer", instructions=_instructions(skills))

    async def get_dataset(
        dataset_id: str,
        select: str | None = None,
        where: str | None = None,
        order: str | None = None,
        group: str | None = None,
        having: str | None = None,
        q: str | None = None,
        limit: int = _PAGE_LIMIT,
        offset: int = 0,
    ) -> str:
        """
        Query a CDC open dataset (data.cdc.gov, Socrata SODA API) and return its rows.

        Pass SoQL clauses without the leading ``$``. String literals use single quotes and
        comparison is case-sensitive, so wrap text columns in ``upper()``, e.g.
        ``where="upper(state)='MARYLAND' AND year >= 2005"``. For dates, compute the bounds
        from today's date and pass ISO literals. Aggregate on the server, e.g.
        ``select="state, count(*) as n", group="state", order="n DESC"``, instead of paging
        through large datasets. Use the field names (not display names) from
        describe_dataset; a bad name returns HTTP 400 ``query.soql.no-such-column``.

        Args:
            dataset_id: The 4x4 id of a dataset or filtered view, e.g. "8zak-ewtm".
            select: Optional columns or expressions ($select), e.g. "count(*) as n".
            where: Optional SoQL condition ($where).
            order: Optional sort ($order), e.g. "year DESC".
            group: Optional group-by columns ($group); put the aggregates in select.
            having: Optional condition on aggregates ($having), e.g. "count(*) > 10".
            q: Optional full-text search across text columns ($q).
            limit: Maximum rows to return (default 100, max 50000). Use 1 to probe.
            offset: Rows to skip, for paging with a stable order (default 0).

        Returns:
            The rows as a JSON list of objects. Numbers come back as strings, and null
            fields are omitted from a row.
        """
        dataset_id = dataset_id.strip().strip("`").lower()
        if not 0 <= limit <= _MAX_LIMIT:
            raise ToolError(f"limit must be between 0 and {_MAX_LIMIT}, got {limit}.")
        if offset < 0:
            raise ToolError(f"offset must be 0 or more, got {offset}.")
        if catalog is not None:
            asset = catalog.get(dataset_id)
            if asset is None:
                raise _unknown(dataset_id, catalog.suggest(dataset_id), len(catalog.assets))
            if not asset.queryable:
                parents = ", ".join(asset.parents) or "its parent dataset"
                raise ToolError(
                    f"'{dataset_id}' ({asset.name}) is a {asset.type} with no data endpoint. "
                    f"Query the dataset it is built on: {parents}."
                )

        params: dict[str, str | int] = {"$limit": limit, "$offset": offset}
        for name, value in (
            ("$select", select),
            ("$where", where),
            ("$order", order),
            ("$group", group),
            ("$having", having),
            ("$q", q),
        ):
            if value:
                params[name] = value
        return await _fetch_dataset(dataset_id, params)

    if catalog is None:
        mcp.tool()(get_dataset)
    else:
        description = f"{inspect.cleandoc(get_dataset.__doc__ or '')}\n\n{_TOOL_HINT}"
        mcp.tool(description=description)(get_dataset)
        _register_discovery_tools(mcp, catalog)

    for skill in skills:
        register_skill(mcp, skill, prompt_name=f"skill-{skill.path.parent.name}")
    return mcp


def _register_discovery_tools(mcp: FastMCP, catalog: SodaCatalog) -> None:
    """Add ``list_datasets`` and ``describe_dataset`` backed by ``catalog``."""
    categories = catalog.categories

    def list_datasets(search: str | None = None, category: str | None = None) -> str:
        """
        List the CDC datasets, filtered views, maps and charts in the topic skills.

        Args:
            search: Optional words that must all appear (case-insensitive) in an asset's id,
                name, description, tags or column names, e.g. "tobacco" or "overdose deaths".
                Omit to list everything.
            category: Optional topic to restrict to: one of the skill folders, e.g. "nchs",
                "ncird", "public_health_infrastructure", "respiratory_viruses",
                "smoking_tobacco" or "vaccinations".

        Returns:
            A header line, then one line per asset grouped by topic, with its type, row
            count, last data update and, for views, the dataset it is built on.
        """
        if category and category not in categories:
            raise ToolError(f"Unknown category '{category}'. Use one of: {', '.join(categories)}.")
        matches = catalog.search(search, category)
        if not matches:
            return f"No CDC assets match '{search}'. Call list_datasets() to list all."
        return format_index(matches, label=_LABEL)

    def describe_dataset(id_or_name: str) -> str:
        """
        Describe one CDC dataset: endpoint, row count, freshness, topics, tags and columns.

        Args:
            id_or_name: A 4x4 dataset id (e.g. "8zak-ewtm"), a URL containing one, or the
                dataset's exact name.

        Returns:
            The dataset's markdown section from the skill, with a column table of field
            names, display names, types and descriptions.
        """
        matches = catalog.find(id_or_name)
        if not matches:
            raise _unknown(id_or_name.strip(), catalog.suggest(id_or_name), len(catalog.assets))
        if len(matches) > 1:
            ids = ", ".join(f"`{a.id}` ({a.category})" for a in matches)
            return f"'{id_or_name}' matches several assets: {ids}. Pass a dataset id."
        asset = matches[0]
        return asset.section or format_index([asset], label=_LABEL)

    mcp.tool()(list_datasets)
    mcp.tool()(describe_dataset)


mcp = create_server(load_nested_skills(_SERVER_DIR) if _LOAD_SKILLS else ())

if __name__ == "__main__":
    mcp.run()
