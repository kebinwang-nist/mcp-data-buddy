"""Dataset catalog parsed from the CDC topic skills (pure, no I/O).

Each topic SKILL.md (generated by :mod:`servers.cdc.build_skills`) has an
``## Endpoint index`` with one row per queryable asset (dataset or filtered view) and a
"Maps and charts" table, plus one ``### <id>`` section per queryable asset with its endpoint,
row count and columns. :func:`parse_catalog` turns them into a :class:`SodaCatalog` used by
the cdc server for discovery and validation.
"""

from __future__ import annotations

import difflib
import logging
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass

logger = logging.getLogger(__name__)

_INDEX_HEADING = "## Endpoint index"
_ASSET_ID = re.compile(r"\b([a-z0-9]{4}-[a-z0-9]{4})\b")
_QUERYABLE_ROW = re.compile(r"^\|\s*\d+\s*\|")
_VISUAL_ROW = re.compile(r"^\|\s*`[a-z0-9]{4}-[a-z0-9]{4}`\s*\|")
_CELL_SPLIT = re.compile(r"(?<!\\)\|")
_QUERYABLE_CELLS = 10
_VISUAL_CELLS = 5
_SECTION_HEADING = re.compile(r"^### ([a-z0-9]{4}-[a-z0-9]{4})[ \t]*$", re.MULTILINE)
_NEXT_HEADING = re.compile(r"^#{2,3} ", re.MULTILINE)


@dataclass(frozen=True, slots=True)
class SodaAsset:
    """One asset of a category skill's index, with its markdown section."""

    id: str
    name: str
    type: str  # dataset, filter, map or chart
    category: str  # skill folder, e.g. "human_resources"
    parents: tuple[str, ...]
    rows: str
    data_updated: str
    update_frequency: str
    section: str

    @property
    def queryable(self) -> bool:
        """Return whether the asset has its own ``/resource/{id}.json`` endpoint."""
        return self.type in ("dataset", "filter")

    def index_line(self) -> str:
        """Return a one-line summary for listings."""
        if not self.queryable:
            built_on = ", ".join(f"`{p}`" for p in self.parents) or "unknown"
            return f"- `{self.id}` {self.name} ({self.type}; no data endpoint, query {built_on})"
        details = [self.type, f"{self.rows} rows", f"updated {self.data_updated}"]
        if self.update_frequency:
            details.append(self.update_frequency.lower())
        if self.parents:
            details.append("view of " + ", ".join(f"`{p}`" for p in self.parents))
        return f"- `{self.id}` {self.name} ({'; '.join(details)})"


@dataclass(frozen=True, slots=True)
class SodaCatalog:
    """All assets documented in the category skills, with lookup helpers."""

    assets: tuple[SodaAsset, ...]

    @property
    def categories(self) -> list[str]:
        """Return the category (skill folder) names, in catalog order."""
        return list(dict.fromkeys(a.category for a in self.assets))

    def get(self, asset_id: str) -> SodaAsset | None:
        """Return the asset with id ``asset_id`` (case-insensitive), or ``None``."""
        wanted = asset_id.strip().strip("`").lower()
        return next((a for a in self.assets if a.id == wanted), None)

    def find(self, id_or_name: str) -> list[SodaAsset]:
        """Return the asset named by an id, a URL containing one, or an exact name."""
        query = id_or_name.strip().strip("`")
        match = _ASSET_ID.search(query.lower())
        if match and (asset := self.get(match.group(1))):
            return [asset]
        lowered = query.lower()
        return [a for a in self.assets if a.name.lower() == lowered]

    def search(self, text: str | None = None, category: str | None = None) -> list[SodaAsset]:
        """Return assets whose id, name or section contain ``text``, optionally in one category.

        All words of ``text`` must appear (case-insensitive). ``None`` or blank matches all.
        """
        assets: Iterable[SodaAsset] = self.assets
        if category:
            assets = [a for a in assets if a.category == category]
        words = (text or "").lower().split()
        return [
            a for a in assets if all(w in f"{a.id} {a.name} {a.section}".lower() for w in words)
        ]

    def suggest(self, id_or_name: str, limit: int = 5) -> list[str]:
        """Return up to ``limit`` ``id (name)`` strings close to ``id_or_name``."""
        query = id_or_name.strip().lower()
        by_id = {a.id: a for a in self.assets}
        by_name = {a.name.lower(): a for a in self.assets}
        found = difflib.get_close_matches(query, list(by_id), n=limit, cutoff=0.6)
        for name in difflib.get_close_matches(query, list(by_name), n=limit, cutoff=0.5):
            found.append(by_name[name].id)
        ids = list(dict.fromkeys(found))[:limit]
        return [f"{i} ({by_id[i].name})" for i in ids]


def _cells(line: str) -> list[str]:
    """Split a markdown table row on unescaped ``|``, unescaping the cells."""
    inner = line.strip().removeprefix("|").removesuffix("|")
    return [cell.strip().replace("\\|", "|") for cell in _CELL_SPLIT.split(inner)]


def _sections(markdown: str) -> dict[str, str]:
    """Map each ``### <id>`` heading to its section text."""
    sections: dict[str, str] = {}
    for match in _SECTION_HEADING.finditer(markdown):
        following = _NEXT_HEADING.search(markdown, match.end())
        end = following.start() if following else len(markdown)
        sections[match.group(1)] = markdown[match.start() : end].rstrip()
    return sections


def parse_catalog(markdown: str, category: str, label: str = "CDC") -> SodaCatalog:
    """Parse one category skill body into a :class:`SodaCatalog`.

    Args:
        markdown: The skill body.
        category: The skill folder name, stored on each asset.
        label: Portal name for log messages, e.g. "CDC".
    """
    start = markdown.find(f"\n{_INDEX_HEADING}\n")
    if start < 0:
        logger.warning("%s skill %s has no endpoint index", label, category)
        return SodaCatalog(assets=())
    end = markdown.find("\n## ", start + len(_INDEX_HEADING) + 2)
    index = markdown[start : end if end >= 0 else len(markdown)]
    sections = _sections(markdown)

    assets: list[SodaAsset] = []
    for line in index.splitlines():
        if _QUERYABLE_ROW.match(line):
            cells = _cells(line)
            if len(cells) != _QUERYABLE_CELLS or not (match := _ASSET_ID.search(cells[1])):
                logger.warning("Skipping malformed index row in %s: %s", category, line)
                continue
            asset_id = match.group(1)
            assets.append(
                SodaAsset(
                    id=asset_id,
                    name=cells[2],
                    type=cells[3],
                    category=category,
                    parents=tuple(_ASSET_ID.findall(cells[4])),
                    rows=cells[5],
                    data_updated=cells[7],
                    update_frequency=cells[8],
                    section=sections.get(asset_id, ""),
                )
            )
        elif _VISUAL_ROW.match(line):
            cells = _cells(line)
            if len(cells) != _VISUAL_CELLS:
                logger.warning("Skipping malformed map/chart row in %s: %s", category, line)
                continue
            parents = re.findall(r"`([a-z0-9]{4}-[a-z0-9]{4})`", cells[3])
            assets.append(
                SodaAsset(
                    id=cells[0].strip("`"),
                    name=cells[1],
                    type=cells[2],
                    category=category,
                    parents=tuple(parents),
                    rows="",
                    data_updated=cells[4],
                    update_frequency="",
                    section="",
                )
            )
    queryable = sum(a.queryable for a in assets)
    if queryable != len(sections):
        logger.warning(
            "Skill %s lists %d queryable assets but has %d sections",
            category,
            queryable,
            len(sections),
        )
    return SodaCatalog(assets=tuple(assets))


def merge_catalogs(catalogs: Sequence[SodaCatalog]) -> SodaCatalog:
    """Combine catalogs, keeping the first occurrence of an id listed in several categories."""
    seen: dict[str, SodaAsset] = {}
    for catalog in catalogs:
        for asset in catalog.assets:
            seen.setdefault(asset.id, asset)
    return SodaCatalog(assets=tuple(seen.values()))


def format_index(assets: Sequence[SodaAsset], label: str = "CDC") -> str:
    """Render ``assets`` grouped by category, one line each, with a ``label`` header.

    Args:
        assets: The assets to list.
        label: Portal name for the header line, e.g. "CDC".
    """
    lines = [
        (
            f"{len(assets)} {label} asset(s). Query a dataset or filter with "
            "get_dataset(dataset_id, ...); maps and charts have no data endpoint."
        )
    ]
    category = None
    for asset in assets:
        if asset.category != category:
            category = asset.category
            lines.append(f"\n{category}:")
        lines.append(asset.index_line())
    return "\n".join(lines)
