"""FDA MCP server: drug and food data from openFDA (api.fda.gov, Elasticsearch-based REST API).

The server loads every endpoint skill ``skills/<folder>/SKILL.md`` (generated by
``build_skills.py``) at import and:

- publishes each as the ``skill://fda-<...>`` resource and the ``skill-<folder>`` prompt, and
  builds the server instructions from their descriptions;
- adds the ``list_datasets`` and ``describe_dataset`` discovery tools, driven by the endpoint
  index and field table of each skill;
- makes ``get_dataset`` reject dataset ids no skill lists (with close-match suggestions)
  before any HTTP call, and add advisory hints for field names the skill doesn't list.

Only ``drug/*`` and ``food/*`` endpoints are served, with or without skills. Without skill
files the server exposes only ``get_dataset``; set ``"load_skills": false`` on its entry in
``server_config.json`` for the same behavior while keeping the files. The optional
``OPENFDA_API_KEY`` (see :mod:`config`) is sent as the Basic-auth username. Regenerate the
skills with ``uv run python -m servers.fda.build_skills``.
"""

import asyncio
import inspect
import json
import logging
import ssl
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import httpx
import truststore
from fastmcp import FastMCP
from fastmcp.exceptions import ToolError

from config import get_openfda_settings
from servers.fda import api
from servers.fda.catalog import FdaCatalog, format_index, merge_catalogs, parse_catalog
from servers.skills import Skill, load_nested_skills, register_skill

logger = logging.getLogger(__name__)

_SERVER_DIR = Path(__file__).resolve().parent
_SERVER_CONFIG = _SERVER_DIR.parents[1] / "server_config.json"
_TIMEOUT_SECONDS = 60.0
_ERROR_TEXT_LIMIT = 1000
_TEXT_FIELD_ERROR = "Text fields are not optimised"

_DISCOVERY_HINT = (
    "Call list_datasets (optionally with a search term or category 'drug' / 'food') to find "
    "an endpoint, describe_dataset(id, field_search=...) to see its fields, then "
    "get_dataset(dataset_id, search, count, sort, fields, limit, skip) to read records. Use "
    "count for aggregates (top terms, counts per date) instead of paging, count on "
    "'<field>.exact' for whole values, and pass fields to keep records small. Read the skill's "
    "usage tips (prompt skill-<folder>) for field quirks; results carry hints for unknown "
    "field names and '.exact' problems."
)
_TOOL_HINT = (
    "Use list_datasets to find valid dataset ids and describe_dataset for an endpoint's "
    "fields. Unknown or out-of-scope ids are rejected with suggestions; unknown field names "
    "come back as hints, not errors."
)


def _load_entry(name: str) -> dict[str, object]:
    """Return the entry of server ``name`` in ``server_config.json``."""
    servers: list[dict[str, object]] = json.loads(_SERVER_CONFIG.read_text(encoding="utf-8"))
    for server in servers:
        if server["name"] == name:
            return server
    raise KeyError(f"No '{name}' entry in {_SERVER_CONFIG}")


_ENTRY = _load_entry("fda")
_ENDPOINTS: dict[str, str] = _ENTRY.get("endpoints", {})  # type: ignore[assignment]
_LOAD_SKILLS = bool(_ENTRY.get("load_skills", True))


def _api_key() -> str | None:
    """Return the configured openFDA API key, or ``None`` when unset or blank."""
    key = get_openfda_settings().openfda_api_key
    value = key.get_secret_value().strip() if key else ""
    return value or None


def _payload(response: httpx.Response) -> dict[str, Any]:
    """Return the JSON object body of ``response``, or an empty dict if it has none."""
    try:
        body = response.json()
    except ValueError:
        return {}
    return body if isinstance(body, dict) else {}


async def _request(
    client: httpx.AsyncClient, dataset_id: str, params: dict[str, str | int]
) -> tuple[api.Outcome, dict[str, Any]]:
    """GET ``{base_url}/{dataset_id}.json``, retrying 429/5xx responses and transport errors.

    Returns:
        The outcome (``ok``, ``empty`` or ``error``) and the parsed JSON body.

    Raises:
        ToolError: When the request is still failing after
            :data:`servers.fda.api.MAX_ATTEMPTS` attempts.
    """
    url = f"{_ENDPOINTS['base_url'].rstrip('/')}/{dataset_id}.json"
    problem = ""
    for attempt in range(1, api.MAX_ATTEMPTS + 1):
        retry_after: str | None = None
        try:
            response = await client.get(url, params=params)
        except httpx.TransportError as exc:
            problem = f"{type(exc).__name__}: {exc}"
        else:
            payload = _payload(response)
            outcome = api.classify(response.status_code, payload)
            if outcome.kind != "retry":
                return outcome, payload
            problem = outcome.message
            retry_after = response.headers.get("Retry-After")
        if attempt < api.MAX_ATTEMPTS:
            delay = api.retry_delay(attempt, retry_after)
            logger.warning(
                "openFDA %s: %s, retry %d/%d in %.0f s",
                dataset_id,
                problem,
                attempt,
                api.MAX_ATTEMPTS - 1,
                delay,
            )
            await asyncio.sleep(delay)
    raise ToolError(
        f"openFDA unavailable for {dataset_id} after {api.MAX_ATTEMPTS} attempts: {problem}"
    )


def _build_catalog(skills: Sequence[Skill]) -> FdaCatalog | None:
    """Merge the catalogs of ``skills``; ``None`` if none of them lists an endpoint."""
    catalog = merge_catalogs([parse_catalog(s.body, s.path.parent.name) for s in skills])
    if not catalog.datasets:
        if skills:
            logger.warning("openFDA skills list no endpoints; get_dataset won't validate")
        return None
    return catalog


def _instructions(skills: Sequence[Skill]) -> str | None:
    """Build the server instructions from the skill descriptions, or ``None`` without skills."""
    if not skills:
        return None
    parts = [
        "openFDA drug and food data (api.fda.gov). Endpoints:",
        *(f"- {s.path.parent.name}: {s.description}" for s in skills),
        _DISCOVERY_HINT,
        "Full references: MCP resources " + ", ".join(s.resource_uri for s in skills) + ".",
    ]
    return "\n\n".join(parts)


def _unknown(what: str, suggestions: list[str], total: int) -> ToolError:
    """Build the error for a dataset id the skills do not list."""
    hint = f" Did you mean: {', '.join(suggestions)}?" if suggestions else ""
    return ToolError(
        f"Unknown openFDA dataset '{what}'.{hint} Call list_datasets to see all {total} endpoints."
    )


def _out_of_scope(what: str) -> ToolError:
    """Build the error for an id outside the drug and food APIs."""
    return ToolError(
        f"'{what}' is not an openFDA drug or food endpoint. This server only serves "
        f"{', '.join(f'{c}/*' for c in api.CATEGORIES)} (e.g. drug/event, food/enforcement)."
    )


def _resolve(dataset_id: str, catalog: FdaCatalog | None) -> str:
    """Return the canonical endpoint id for ``dataset_id``, or raise a ToolError."""
    if catalog is not None and (dataset := catalog.get(dataset_id)) is not None:
        return dataset.id
    normalized = api.normalize_dataset_id(dataset_id)
    if not api.in_scope(normalized):
        raise _out_of_scope(dataset_id.strip())
    if catalog is not None:
        raise _unknown(normalized, catalog.suggest(dataset_id), len(catalog.datasets))
    return normalized


def _validate(
    count: str | None,
    sort: str | None,
    fields: list[str] | None,
    limit: int | None,
    skip: int,
) -> int:
    """Check the query arguments and return the ``limit`` to send.

    Raises:
        ToolError: For a blank ``count``, ``count`` combined with ``skip``/``sort``/``fields``,
            or ``limit``/``skip`` out of range.
    """
    if count is not None and not count.strip():
        raise ToolError("count must be a field name, e.g. 'classification.exact'; got blank.")
    if count:
        conflicts = [
            name
            for name, used in (("skip", skip > 0), ("sort", bool(sort)), ("fields", bool(fields)))
            if used
        ]
        if conflicts:
            raise ToolError(
                f"count cannot be combined with {', '.join(conflicts)}; count returns "
                "term/count pairs, not records."
            )
    low = 1 if count else 0
    if limit is None:
        limit = api.DEFAULT_COUNT_LIMIT if count else api.DEFAULT_LIMIT
    if not low <= limit <= api.MAX_LIMIT:
        raise ToolError(f"limit must be between {low} and {api.MAX_LIMIT}, got {limit}.")
    if not 0 <= skip <= api.MAX_SKIP:
        raise ToolError(f"skip must be between 0 and {api.MAX_SKIP}, got {skip}.")
    return limit


def _hints(
    catalog: FdaCatalog | None,
    dataset_id: str,
    search: str | None,
    count: str | None,
    sort: str | None,
    fields: list[str] | None,
) -> list[str]:
    """Return advisory hints for field names the skill does not list (none without skills)."""
    if catalog is None:
        return []
    paths = [
        *(api.search_fields(search) if search else []),
        *([count.strip()] if count else []),
        *([sort.split(":", 1)[0].strip()] if sort else []),
        *(fields or []),
    ]
    return api.field_hints(paths, catalog.field_names(dataset_id))


def _hint_text(hints: list[str]) -> str:
    """Render hints as a suffix for an error message."""
    return f" Hints: {' '.join(hints)}" if hints else ""


def create_server(skills: Sequence[Skill] = ()) -> FastMCP:
    """Build the FDA FastMCP server, using the skills if given.

    Args:
        skills: Endpoint skills (``skills/<folder>/SKILL.md``) whose endpoint indexes and field
            tables back discovery, id validation and field hints. Empty for the plain
            ``get_dataset``-only server.

    Returns:
        The configured server.
    """
    catalog = _build_catalog(skills)
    mcp = FastMCP("FdaServer", instructions=_instructions(skills))

    async def get_dataset(
        dataset_id: str,
        search: str | None = None,
        count: str | None = None,
        sort: str | None = None,
        fields: list[str] | None = None,
        limit: int | None = None,
        skip: int = 0,
    ) -> str:
        """
        Query an openFDA drug or food endpoint (api.fda.gov) and return records or counts.

        ``search`` uses openFDA (Elasticsearch) syntax: ``field:term`` or ``field:"a phrase"``,
        joined with AND / OR / NOT, ranges ``field:[A TO B]`` with YYYYMMDD dates, and
        ``_exists_:field`` / ``_missing_:field``. Write spaces as spaces, not ``+``. The plain
        field matches words case-insensitively; ``field.exact`` matches the whole value
        case-sensitively. ``count`` returns ``[{"term": ..., "count": n}]`` (date fields:
        ``{"time": ..., "count": n}``) for one field, most frequent first; count on
        ``<field>.exact`` for whole values. Aggregate with count instead of paging.

        Args:
            dataset_id: Endpoint id, e.g. "drug/event", "drug/label", "food/enforcement". A
                URL or skill folder name (e.g. "drug_adverse_events") also works.
            search: Optional filter, e.g.
                'classification:"Class I" AND report_date:[20250101 TO 20251231]'.
            count: Optional field to count instead of returning records, e.g.
                "patient.reaction.reactionmeddrapt.exact".
            sort: Optional "field:asc" or "field:desc", e.g. "report_date:desc".
            fields: Optional dotted paths to keep in each record (client-side), e.g.
                ["openfda.brand_name", "boxed_warning"]. Use it on large records (drug/label).
            limit: Records to return (default 10, 0-1000; 0 gives only the total) or count
                terms (default 100, 1-1000; 1000 needs OPENFDA_API_KEY).
            skip: Records to skip for paging (0-25000; not with count).

        Returns:
            JSON. Records: {"dataset", "total", "skip", "limit", "last_updated", "results"}.
            Count: {"dataset", "count", "last_updated", "results"}. No matches is not an
            error: {"dataset", "total": 0, "results": [], "note"}. A "hints" list flags
            field names the skill does not list (a misspelled field also gives no matches).
        """
        resolved = _resolve(dataset_id, catalog)
        limit = _validate(count, sort, fields, limit, skip)
        count = count.strip() if count else None
        hints = _hints(catalog, resolved, search, count, sort, fields)

        params: dict[str, str | int] = {"limit": limit}
        if search:
            params["search"] = search
        if count:
            params["count"] = count
        if sort:
            params["sort"] = sort
        if skip:
            params["skip"] = skip

        async with httpx.AsyncClient(
            timeout=_TIMEOUT_SECONDS,
            verify=truststore.SSLContext(ssl.PROTOCOL_TLS_CLIENT),
            auth=api.basic_auth(_api_key()),
        ) as client:
            outcome, payload = await _request(client, resolved, params)

        if outcome.kind == "error":
            if count and not count.endswith(".exact") and _TEXT_FIELD_ERROR in outcome.message:
                hints.append(f"Count `{count}.exact` instead.")
            raise ToolError(
                f"openFDA error for {resolved}: {outcome.message[:_ERROR_TEXT_LIMIT]}"
                f"{_hint_text(hints)}"
            )

        result: dict[str, Any]
        if outcome.kind == "empty":
            if count and count.endswith(".exact"):
                hints.append(
                    f"`{api.strip_exact(count)}` may have no `.exact` subfield; retry without "
                    "`.exact`."
                )
            result = {"dataset": resolved, "total": 0, "results": [], "note": outcome.message}
        else:
            meta = payload.get("meta") or {}
            rows = payload.get("results") or []
            if count:
                result = {
                    "dataset": resolved,
                    "count": count,
                    "last_updated": meta.get("last_updated"),
                    "results": rows,
                }
            else:
                page = meta.get("results") or {}
                if fields:
                    rows = [api.project(row, fields) for row in rows if isinstance(row, dict)]
                result = {
                    "dataset": resolved,
                    "total": page.get("total"),
                    "skip": page.get("skip", skip),
                    "limit": page.get("limit", limit),
                    "last_updated": meta.get("last_updated"),
                    "results": rows,
                }
        if hints:
            result["hints"] = hints
        return json.dumps(result)

    if catalog is None:
        mcp.tool()(get_dataset)
    else:
        description = f"{inspect.cleandoc(get_dataset.__doc__ or '')}\n\n{_TOOL_HINT}"
        mcp.tool(description=description)(get_dataset)
        _register_discovery_tools(mcp, catalog)

    for skill in skills:
        register_skill(mcp, skill, prompt_name=f"skill-{skill.path.parent.name}")
    return mcp


def _filter_fields(section: str, field_search: str) -> str:
    """Keep the section's header lines and only the field rows containing all words."""
    words = field_search.lower().split()
    kept: list[str] = []
    total = matched = 0
    for line in section.splitlines():
        if line.startswith("| `"):
            total += 1
            if all(w in line.lower() for w in words):
                matched += 1
                kept.append(line)
        else:
            kept.append(line)
    kept.append("")
    kept.append(f"{matched} of {total} fields match '{field_search}'.")
    return "\n".join(kept)


def _register_discovery_tools(mcp: FastMCP, catalog: FdaCatalog) -> None:
    """Add ``list_datasets`` and ``describe_dataset`` backed by ``catalog``."""
    categories = catalog.categories

    def list_datasets(search: str | None = None, category: str | None = None) -> str:
        """
        List the openFDA drug and food endpoints in the skills.

        Args:
            search: Optional words that must all appear (case-insensitive) in an endpoint's
                id, name, skill folder or section (which includes its field names), e.g.
                "recall" or "boxed_warning". Omit to list everything.
            category: Optional API category to restrict to: "drug" or "food".

        Returns:
            A header line, then one line per endpoint grouped by category, with its record
            count, last data update, number of fields and skill prompt.
        """
        if category and category not in categories:
            raise ToolError(f"Unknown category '{category}'. Use one of: {', '.join(categories)}.")
        matches = catalog.search(search, category)
        if not matches:
            return f"No openFDA endpoints match '{search}'. Call list_datasets() to list all."
        return format_index(matches)

    def describe_dataset(id_or_name: str, field_search: str | None = None) -> str:
        """
        Describe one openFDA endpoint: URL, record count, freshness, example queries, fields.

        Args:
            id_or_name: An endpoint id (e.g. "drug/event"), a URL, a skill folder (e.g.
                "drug_adverse_events") or the endpoint's exact name.
            field_search: Optional words that must all appear (case-insensitive) in a field
                row, e.g. "boxed" or "date". Only matching field rows are returned. Use it on
                drug/label, whose full field table is very large.

        Returns:
            The endpoint's markdown section from the skill, with a field table of dotted
            names, types, the `.exact` flag, descriptions and possible values.
        """
        matches = catalog.find(id_or_name)
        if not matches:
            raise _unknown(id_or_name.strip(), catalog.suggest(id_or_name), len(catalog.datasets))
        dataset = matches[0]
        section = dataset.section or format_index([dataset])
        if field_search and field_search.strip():
            return _filter_fields(section, field_search.strip())
        return section

    mcp.tool()(list_datasets)
    mcp.tool()(describe_dataset)


mcp = create_server(load_nested_skills(_SERVER_DIR) if _LOAD_SKILLS else ())

if __name__ == "__main__":
    mcp.run()
