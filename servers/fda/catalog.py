"""openFDA endpoint catalog parsed from the FDA endpoint skills (pure, no I/O).

Each endpoint SKILL.md (generated by :mod:`servers.fda.build_skills`) has an
``## Endpoint index`` with one 6-cell row for its endpoint, and one ``### <id>`` section
(e.g. ``### drug/event``) with the endpoint, record count, sample-record field names and a
field table. :func:`parse_catalog` turns them into an :class:`FdaCatalog` used by the FDA
server for discovery and advisory field-name checks.
"""

from __future__ import annotations

import difflib
import logging
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass

from servers.fda.api import normalize_dataset_id

logger = logging.getLogger(__name__)

_INDEX_HEADING = "## Endpoint index"
_INDEX_ROW = re.compile(r"^\|\s*`((?:drug|food)/[a-z0-9]+)`\s*\|")
_INDEX_CELLS = 6
_CELL_SPLIT = re.compile(r"(?<!\\)\|")
_SECTION_HEADING = re.compile(r"^### ((?:drug|food)/[a-z0-9]+)[ \t]*$", re.MULTILINE)
_NEXT_HEADING = re.compile(r"^#{2,3} ", re.MULTILINE)
_FIELD_ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|")
_EXTRA_LINE = "- Also returned by the API (not in the field definitions):"
_BACKTICKED = re.compile(r"`([^`]+)`")


@dataclass(frozen=True, slots=True)
class FdaField:
    """One field of an endpoint's field table."""

    name: str
    type: str
    exact: bool


@dataclass(frozen=True, slots=True)
class FdaDataset:
    """One openFDA endpoint from a skill's index, with its markdown section."""

    id: str  # e.g. "drug/event"
    name: str
    category: str  # "drug" or "food"
    folder: str  # skill folder, e.g. "drug_adverse_events"
    records: str
    fields_count: str
    last_updated: str
    fields: tuple[FdaField, ...]
    section: str
    extra_fields: tuple[str, ...] = ()

    def index_line(self) -> str:
        """Return a one-line summary for listings."""
        return (
            f"- `{self.id}` {self.name} ({self.category}; {self.records} records; "
            f"updated {self.last_updated}; {self.fields_count} fields; "
            f"prompt skill-{self.folder})"
        )


@dataclass(frozen=True, slots=True)
class FdaCatalog:
    """All endpoints documented in the FDA skills, with lookup helpers."""

    datasets: tuple[FdaDataset, ...]

    @property
    def categories(self) -> list[str]:
        """Return the API categories (``drug``, ``food``), in catalog order."""
        return list(dict.fromkeys(d.category for d in self.datasets))

    def get(self, text: str) -> FdaDataset | None:
        """Return the dataset named by an id, path, URL or skill folder name, or ``None``."""
        wanted = normalize_dataset_id(text)
        return next((d for d in self.datasets if wanted in (d.id, d.folder)), None)

    def find(self, id_or_name: str) -> list[FdaDataset]:
        """Return the dataset named by an id, URL, folder or exact name (case-insensitive)."""
        dataset = self.get(id_or_name)
        if dataset is not None:
            return [dataset]
        lowered = id_or_name.strip().strip("`").lower()
        return [d for d in self.datasets if d.name.lower() == lowered]

    def search(self, text: str | None = None, category: str | None = None) -> list[FdaDataset]:
        """Return datasets whose id, name, folder or section contain all words of ``text``.

        Matching is case-insensitive. ``None`` or blank matches all; ``category`` restricts
        to ``drug`` or ``food``.
        """
        datasets: Iterable[FdaDataset] = self.datasets
        if category:
            datasets = [d for d in datasets if d.category == category]
        words = (text or "").lower().split()
        return [
            d
            for d in datasets
            if all(w in f"{d.id} {d.name} {d.folder} {d.section}".lower() for w in words)
        ]

    def suggest(self, text: str, limit: int = 5) -> list[str]:
        """Return up to ``limit`` ``id (name)`` strings close to ``text``."""
        query = normalize_dataset_id(text)
        by_key: dict[str, FdaDataset] = {}
        for d in self.datasets:
            by_key.setdefault(d.id, d)
            by_key.setdefault(d.folder, d)
            by_key.setdefault(d.name.lower(), d)
        found = [
            by_key[k].id
            for k in difflib.get_close_matches(query, list(by_key), n=limit * 3, cutoff=0.5)
        ]
        ids = list(dict.fromkeys(found))[:limit]
        names = {d.id: d.name for d in self.datasets}
        return [f"{i} ({names[i]})" for i in ids]

    def field_names(self, dataset_id: str) -> frozenset[str]:
        """Return the documented and sample-only field names of ``dataset_id`` (empty if unknown)."""
        dataset = self.get(dataset_id)
        if dataset is None:
            return frozenset()
        return frozenset([*(f.name for f in dataset.fields), *dataset.extra_fields])


def _cells(line: str) -> list[str]:
    """Split a markdown table row on unescaped ``|``, unescaping the cells."""
    inner = line.strip().removeprefix("|").removesuffix("|")
    return [cell.strip().replace("\\|", "|") for cell in _CELL_SPLIT.split(inner)]


def _sections(markdown: str) -> dict[str, str]:
    """Map each ``### <id>`` heading to its section text."""
    sections: dict[str, str] = {}
    for match in _SECTION_HEADING.finditer(markdown):
        following = _NEXT_HEADING.search(markdown, match.end())
        end = following.start() if following else len(markdown)
        sections[match.group(1)] = markdown[match.start() : end].rstrip()
    return sections


def _fields(section: str) -> tuple[FdaField, ...]:
    """Read the field table rows of one section."""
    fields: list[FdaField] = []
    for line in section.splitlines():
        if not _FIELD_ROW.match(line):
            continue
        cells = _cells(line)
        if len(cells) < 3:
            continue
        fields.append(FdaField(name=cells[0].strip("`"), type=cells[1], exact=cells[2] == "yes"))
    return tuple(fields)


def _extra_fields(section: str) -> tuple[str, ...]:
    """Read the "Also returned by the API" field names of one section."""
    for line in section.splitlines():
        if line.startswith(_EXTRA_LINE):
            return tuple(_BACKTICKED.findall(line.removeprefix(_EXTRA_LINE)))
    return ()


def parse_catalog(markdown: str, folder: str) -> FdaCatalog:
    """Parse one endpoint skill body into an :class:`FdaCatalog`.

    Args:
        markdown: The skill body.
        folder: The skill folder name, stored on each dataset.

    Returns:
        The catalog. Problems (no index, malformed rows, an index row without a section) are
        logged as warnings, never raised.
    """
    start = markdown.find(f"\n{_INDEX_HEADING}\n")
    if start < 0:
        logger.warning("openFDA skill %s has no endpoint index", folder)
        return FdaCatalog(datasets=())
    end = markdown.find("\n## ", start + len(_INDEX_HEADING) + 2)
    index = markdown[start : end if end >= 0 else len(markdown)]
    sections = _sections(markdown)

    datasets: list[FdaDataset] = []
    for line in index.splitlines():
        match = _INDEX_ROW.match(line)
        if not match:
            continue
        cells = _cells(line)
        if len(cells) != _INDEX_CELLS:
            logger.warning("Skipping malformed index row in %s: %s", folder, line)
            continue
        dataset_id = match.group(1)
        section = sections.get(dataset_id, "")
        if not section:
            logger.warning("openFDA skill %s lists %s but has no section", folder, dataset_id)
        datasets.append(
            FdaDataset(
                id=dataset_id,
                name=cells[1],
                category=cells[2],
                folder=folder,
                records=cells[3],
                fields_count=cells[4],
                last_updated=cells[5],
                fields=_fields(section),
                section=section,
                extra_fields=_extra_fields(section),
            )
        )
    return FdaCatalog(datasets=tuple(datasets))


def merge_catalogs(catalogs: Sequence[FdaCatalog]) -> FdaCatalog:
    """Combine catalogs, keeping the first occurrence of an id listed in several skills."""
    seen: dict[str, FdaDataset] = {}
    for catalog in catalogs:
        for dataset in catalog.datasets:
            seen.setdefault(dataset.id, dataset)
    return FdaCatalog(datasets=tuple(seen.values()))


def format_index(datasets: Sequence[FdaDataset]) -> str:
    """Render ``datasets`` grouped by category, one line each, with a header line."""
    lines = [
        (
            f"{len(datasets)} openFDA dataset(s). Query one with "
            "get_dataset(dataset_id, search, count, ...)."
        )
    ]
    category = None
    for dataset in sorted(datasets, key=lambda d: d.category):
        if dataset.category != category:
            category = dataset.category
            lines.append(f"\n{category}:")
        lines.append(dataset.index_line())
    return "\n".join(lines)
